#!/usr/bin/env python3
"""Generate the gzip-compressed web interface served by the grinder.

The page source stays readable in src/network/device_page.h. Before every
PlatformIO build this script writes src/network/device_page_gz.h with:

  * SMART_GRIND_DEVICE_PAGE_GZ      - the page compressed with gzip
  * SMART_GRIND_DEVICE_PAGE_GZ_LEN  - its length in bytes
  * SMART_GRIND_DEVICE_PAGE_ETAG    - a content hash so browsers can cache the
                                      page and revalidate it with a 304 reply

The file is only rewritten when its content changes, so unchanged pages do not
trigger recompilation.
"""

import gzip
import hashlib
import os
import sys

PAGE_SOURCE = os.path.join("src", "network", "device_page.h")
PAGE_OUTPUT = os.path.join("src", "network", "device_page_gz.h")
RAW_START = 'R"WEB('
RAW_END = ')WEB"'


def extract_page(source_text):
    """Return the exact bytes of the raw string literal the firmware serves."""
    start = source_text.index(RAW_START) + len(RAW_START)
    end = source_text.index(RAW_END, start)
    return source_text[start:end].encode("utf-8")


def render_header(page_bytes):
    compressed = gzip.compress(page_bytes, compresslevel=9, mtime=0)
    etag = hashlib.sha256(page_bytes).hexdigest()[:16]
    rows = []
    for offset in range(0, len(compressed), 20):
        chunk = compressed[offset:offset + 20]
        rows.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    body = "\n".join(rows)
    return (
        "#pragma once\n\n"
        "// Generated by tools/build-scripts/web_page_assets.py from device_page.h.\n"
        "// Do not edit manually.\n\n"
        "#include <Arduino.h>\n"
        "#include <cstddef>\n"
        "#include <cstdint>\n\n"
        f'inline constexpr char SMART_GRIND_DEVICE_PAGE_ETAG[] = "\\"{etag}\\"";\n'
        f"inline constexpr size_t SMART_GRIND_DEVICE_PAGE_GZ_LEN = {len(compressed)};\n"
        "inline constexpr uint8_t SMART_GRIND_DEVICE_PAGE_GZ[] PROGMEM = {\n"
        f"{body}\n"
        "};\n"
    )


def generate(project_dir):
    source_path = os.path.join(project_dir, PAGE_SOURCE)
    output_path = os.path.join(project_dir, PAGE_OUTPUT)
    with open(source_path, encoding="utf-8") as handle:
        header = render_header(extract_page(handle.read()))
    try:
        with open(output_path, encoding="utf-8") as handle:
            if handle.read() == header:
                return output_path
    except FileNotFoundError:
        pass
    with open(output_path, "w", encoding="utf-8") as handle:
        handle.write(header)
    print(f"Generated {PAGE_OUTPUT}")
    return output_path


try:
    Import("env")  # noqa: F821 - provided by PlatformIO
    generate(env.get("PROJECT_DIR", os.getcwd()))  # noqa: F821
except NameError:
    if __name__ == "__main__":
        root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        generate(sys.argv[1] if len(sys.argv) > 1 else root)
